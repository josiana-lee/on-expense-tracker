import { describe, expect, it } from 'vitest';

import { parseCsv } from './csv';

/* 가져오기의 맨 앞단이다. 여기서 한 칸이 밀리면 금액 자리에 카테고리가
   들어가고, 그게 수천 건이 된다. */
describe('parseCsv', () => {
  it('쉼표로 칸을 나누고 줄로 행을 나눈다', () => {
    expect(parseCsv('a,b\n1,2')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  /* 금액이 "151,086"으로 적혀 오는 파일이 있다. 따옴표 안의 쉼표를 칸
     구분으로 읽으면 한 줄이 통째로 밀린다. */
  it('따옴표 안의 쉼표는 칸을 나누지 않는다', () => {
    expect(parseCsv('"151,086",식비')).toEqual([['151,086', '식비']]);
  });

  it('따옴표 안의 두 겹 따옴표는 한 겹으로 푼다', () => {
    expect(parseCsv('"그는 ""안녕"" 했다",b')).toEqual([['그는 "안녕" 했다', 'b']]);
  });

  /* 메모에 줄바꿈이 들어간 기록이 있을 수 있다. 따옴표 안이면 같은 행이다. */
  it('따옴표 안의 줄바꿈은 행을 나누지 않는다', () => {
    expect(parseCsv('"두\n줄",b')).toEqual([['두\n줄', 'b']]);
  });

  it('CRLF 줄바꿈을 LF와 같게 읽는다', () => {
    expect(parseCsv('a,b\r\n1,2')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  /* 엑셀이 저장한 파일은 맨 앞에 BOM이 붙는다. 그대로 두면 첫 열 이름이
     "﻿사용자"가 되어 헤더 판별이 전부 빗나간다. */
  it('맨 앞 BOM을 떼어낸다', () => {
    expect(parseCsv('﻿사용자,거래일')).toEqual([['사용자', '거래일']]);
  });

  /* 인치를 뜻하는 27" 처럼 칸 가운데 든 따옴표다. 이걸 인용 시작으로 읽으면 다음
     줄들이 한 칸으로 삼켜지고, 그 칸 뒤의 모든 칸이 밀려서 엉뚱한 이름의 결제수단이
     새로 만들어진다 — 읽지 못한 줄이 0건으로 보인 채로. 따옴표는 칸의 맨 앞에서만
     인용을 연다(RFC 4180). */
  it('칸 가운데의 따옴표는 그냥 글자다', () => {
    expect(parseCsv('a,27" 모니터,b\nc,d,e')).toEqual([
      ['a', '27" 모니터', 'b'],
      ['c', 'd', 'e'],
    ]);
  });

  it('빈 줄은 버린다', () => {
    expect(parseCsv('a,b\n\n1,2\n')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  it('빈 칸도 칸으로 센다', () => {
    expect(parseCsv('a,,c')).toEqual([['a', '', 'c']]);
  });
});
