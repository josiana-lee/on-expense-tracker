import type { DateStr, TimeStr } from '../types';

/** 어떤 가계부에서 왔든 이 모양으로 바꾼 뒤에 공통 경로를 탄다.
 *
 *  여기까지가 "읽기"고 그 뒤가 "앉히기"다. 앱마다 다른 건 파일을 이 모양으로
 *  바꾸는 부분뿐이고, 분류를 짝짓고 할부를 묶고 기록을 만드는 일은 한 벌만
 *  있다 — 두 번째 앱부터 매핑 표 하나로 끝나는 이유다.
 *
 *  카테고리와 결제수단은 **이름 그대로** 들고 온다. 여기서 우리 id로 바꾸지
 *  않는 이유는, 무엇을 무엇에 짝지을지는 사용자가 미리보기에서 정하기
 *  때문이다 — 읽는 쪽이 멋대로 정하면 그 결정이 화면에 보이지 않는다. */
/* 지출만 담는다. 이 앱에는 수입을 보여줄 화면이 없어서, 수입을 넣으면 달력 일별
   목록에 지출 줄과 똑같은 모양으로 뜨는데 일·월 합계에서는 빠진다 — 보이는 것과
   합계가 안 맞는 상태가 된다. 그래서 어댑터가 수입을 알아보면 넣지 않고
   ImportParse.income으로 세기만 한다. */
export type ImportRow = {
  date: DateStr;
  /** 원본에 시각이 있으면. 없으면 비워두고, 커밋이 00:00으로 채운다. */
  time?: TimeStr;
  /** 원 단위 정수. 쉼표·통화 기호는 읽는 쪽에서 이미 떼어냈다. */
  amount: number;
  /** 원본 앱의 분류명. 우리 카테고리 id가 아니다. 상위·하위를 가진 앱이면 기록에 붙은
   *  쪽, 곧 하위 분류다. */
  categoryName: string;
  /** 그 분류의 상위 분류. 하위 분류를 쓴 기록에만 있다.
   *
   *  하위 분류는 이름이 우리 카테고리와 같을 때만 쓸 만하다. 안 맞으면 상위로 묶는다 —
   *  하위를 그대로 물으면 쓰는 만큼 질문이 늘어난다(어느 앱의 기본 지출 분류는 상위
   *  12개, 하위 38개). 어느 쪽으로 갈지는 우리 카테고리를 봐야 정해져서, 읽는 쪽은 둘
   *  다 넘기고 planImport가 고른다. */
  parentName?: string;
  /** 세부항목. 직접 입력의 세부항목 칸과 같은 자리 — 원본의 **하위 분류**다. 칩에서 고르는
   *  칸이라 글자를 따로 고칠 수 없으니, 제목이 될 글은 여기가 아니라 `memo`에 둔다. */
  label?: string;
  /** 메모. 직접 입력의 메모 칸과 같은 자리이고 **기록의 제목이 되는 글**이다 — 원본의
   *  "내역"(과 원본에 따로 메모 칸이 있으면 그것까지)을 담는다. 내역을 세부항목 칸에 넣으면
   *  수정 화면에서 고칠 수 없고 목록 규칙도 직접 입력과 갈라진다. */
  memo?: string;
  /** 원본 앱의 결제수단 이름. */
  paymentName: string;
  paymentKind: 'cash' | 'credit' | 'debit';
  /** 할부 회차라면. groupKey는 같은 결제에서 나온 행끼리 같은 값이어야
   *  하고, 그 안에서 no가 1..months로 채워지면 한 묶음으로 복원된다. */
  installment?: { groupKey: string; no: number; months: number };
};

/** 파일 하나를 읽은 결과. */
export type ImportParse = {
  /** 화면에 보일 출처 이름. "위플 가계부" 처럼. */
  source: string;
  rows: ImportRow[];
  /** 파일에서 알아봤지만 **일부러 넣지 않은** 수입 건수. 조용히 버리면 건수가 왜
   *  모자란지 알 수 없으므로 미리보기에서 말해준다. */
  income: number;
  /** 파일 내용의 지문. 같은 파일을 두 번 가져오지 않게 알아보는 데 쓴다. 만들 수 없는
   *  환경이면 없다. */
  fingerprint?: string;
  /** 읽다가 버린 줄 수. 0이 아니면 미리보기에서 말해준다 — 조용히 버리면
   *  사용자는 건수가 왜 모자란지 알 수 없다. */
  skipped: number;
};
